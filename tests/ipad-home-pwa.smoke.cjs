// Run: node tests/ipad-home-pwa.smoke.cjs
// Static regression for iPad Home breakpoint and public PWA update contract.
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.join(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
const css=read("assets/home-p0a.css");
const readerCss=read("assets/mobile-reader.css");
const script=read("assets/experience.js");
const html=read("index.html");
const sw=read("sw.js");
const version=read("assets/app-version.js");
const tablet=css.slice(css.indexOf("/* HOME-IPAD-1032-R1"),css.indexOf("/* iPad / landscape tablet reading density"));
assert.match(tablet,/@media \(min-width:1001px\) and \(max-width:1100px\)/);
assert.match(tablet,/\.app-shell\s*\{display:block/);
assert.match(tablet,/\.app-shell > \.sidebar\s*\{display:none/);
assert.match(tablet,/\.site-header \.top-nav,\.site-header \.header-pill\s*\{display:none/);
assert.match(tablet,/\.mobile-bottom-nav\s*\{[^}]*display:grid;[^}]*grid-template-columns:repeat\(3,/s);
assert.match(tablet,/\.manual-grid\s*\{grid-template-columns:repeat\(2,/);
assert.match(css,/@media \(min-width:851px\) and \(max-width:1100px\)/);
assert.match(css,/\.category-chips button\s*\{min-height:44px;/);
assert.match(readerCss,/UX-P0D-R3/,"Reader iPad layout remains intact");
assert.match(html,/id="appUpdateNotice"/);
assert.match(html,/id="checkAppUpdate"/);
assert.match(html,/id="appUpdateStatus"/);
assert.match(script,/updateViaCache: "none"/);
assert.match(script,/registration\.addEventListener\("updatefound"/);
assert.match(script,/window\.addEventListener\("pageshow"/);
assert.match(script,/window\.addEventListener\("focus"/);
assert.match(script,/document\.addEventListener\("visibilitychange"/);
assert.match(script,/navigator\.serviceWorker\.addEventListener\("controllerchange"/);
assert.match(script,/waiting\.postMessage\(\{ type: "SKIP_WAITING" \}\)/);
assert.match(sw,/importScripts\("\.\/assets\/app-version\.js"\)/);
assert.match(sw,/CACHE_VERSION = "wd-manual-public-" \+ self.WD_BOOKS_VERSION/);
assert.match(version,/WD_BOOKS_VERSION = "1\.3\.37"/);
assert.ok(!script.includes("localStorage.clear()"),"Update must not clear personal reader data");
console.log("PASS: iPad home responsive shell / PWA detection version contract");
